import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const previewUrl = process.env.CRITICAL_CSS_URL || 'http://127.0.0.1:4173/';
const outputPath = path.resolve('src/styles/landing-critical.generated.css');
const variants = [{ width: 390, height: 844, theme: 'light' }];

const browser = await chromium.launch({ headless: true });
const coverageByUrl = new Map();

try {
  for (const variant of variants) {
    const context = await browser.newContext({
      viewport: { width: variant.width, height: variant.height },
    });
    await context.addInitScript((theme) => {
      window.localStorage.setItem('vite-ui-theme', theme);
    }, variant.theme);

    const page = await context.newPage();
    await page.coverage.startCSSCoverage({ resetOnNavigation: false });
    await page.goto(previewUrl, { waitUntil: 'networkidle' });
    await page.locator('h1').waitFor({ state: 'visible' });
    await page.getByRole('button', { name: 'Open menu' }).click();
    await page.getByRole('link', { name: 'Blog', exact: true }).waitFor({ state: 'visible' });
    await page.getByRole('button', { name: 'Accept All', exact: true }).waitFor({
      state: 'visible',
      timeout: 5000,
    });

    const coverage = await page.coverage.stopCSSCoverage();
    for (const entry of coverage) {
      if (!entry.url.includes('/assets/index-') || !entry.url.endsWith('.css')) continue;
      const current = coverageByUrl.get(entry.url) || { text: entry.text, ranges: [] };
      current.ranges.push(...entry.ranges);
      coverageByUrl.set(entry.url, current);
    }

    await context.close();
  }
} finally {
  await browser.close();
}

const entries = [...coverageByUrl.values()];
if (entries.length !== 1) {
  throw new Error(`Expected one application stylesheet, found ${entries.length}.`);
}

const [{ text, ranges }] = entries;
const mergedRanges = ranges
  .sort((a, b) => a.start - b.start)
  .reduce((merged, range) => {
    const previous = merged.at(-1);
    if (!previous || range.start > previous.end) {
      merged.push({ ...range });
    } else {
      previous.end = Math.max(previous.end, range.end);
    }
    return merged;
  }, []);

const fontFaceRules = text.match(/@font-face\s*\{[^}]+\}/g) || [];
const fontFaceBlock = fontFaceRules.join('\n');
const bodyCss = mergedRanges.map(({ start, end }) => text.slice(start, end)).join('');
const criticalCss = fontFaceBlock ? `${fontFaceBlock}\n${bodyCss}` : bodyCss;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `/* Generated by scripts/generate-landing-critical-css.mjs. */\n${criticalCss}\n`
);

console.log(
  `Wrote ${criticalCss.length} bytes of critical landing CSS from ${mergedRanges.length} ranges.`
);
