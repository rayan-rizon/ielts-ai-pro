  <h2>Start with what the examiner actually assesses</h2>
  <p>IELTS Speaking is assessed across the whole test using four equally weighted criteria: fluency and coherence, lexical resource, grammatical range and accuracy, and pronunciation. This article focuses on two criteria, but improving them does not guarantee a particular overall band if another area remains weaker.</p>
  <p>In the public Speaking descriptors, Band 7 allows some errors alongside flexible language and many controlled structures. Band 8 requires broader, more reliable control: vocabulary is used readily and precisely, paraphrase is effective, and most sentences are accurate. The practical direction is consistency, not theatrical complexity.</p>

