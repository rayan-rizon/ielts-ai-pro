  <p>You finish a Task 2 essay with a minute left, reread the first body paragraph, and realise every sentence is individually understandable—but the paragraph still feels jumpy. Adding <em>moreover</em> or <em>therefore</em> will not repair a missing relationship between the ideas.</p>
