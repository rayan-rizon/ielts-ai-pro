  <h2>A worked paragraph repair</h2>
  <p><strong>Jumpy version:</strong> “Traffic charges reduce congestion. Moreover, public transport can be unreliable. Therefore, people use cars. For example, buses are late.”</p>
  <p>The vocabulary is not the main problem. The relationships contradict one another: the first sentence supports charging, then the paragraph moves to unreliable buses without explaining whether that is a cause, a limitation, or a solution.</p>
  <p><strong>Repaired logic:</strong> “Charging drivers can reduce congestion by discouraging optional journeys at peak times. With fewer cars on central roads, buses are more likely to keep to their schedules. This improvement can make public transport a realistic alternative for commuters who currently drive because they fear arriving late.”</p>
  <p>The repaired version uses ordinary vocabulary. It is clearer because each sentence grows from the previous one: policy, mechanism, result, and practical consequence.</p>

  <aside><p><strong>Two-sentence test:</strong> cover every linker and read only the nouns and verbs. If the logic disappears, the paragraph needs better development—not more connective phrases.</p></aside>

  <h2>Run a four-colour revision</h2>
  <p>After one timed essay, mark the paragraph by function. You can use colours on paper or simple labels in a document.</p>
  <ul>
    <li><strong>P:</strong> the central point;</li>
    <li><strong>W:</strong> the reason or mechanism;</li>
    <li><strong>R:</strong> the result or implication;</li>
    <li><strong>E:</strong> the example or evidence.</li>
  </ul>
  <p>If a paragraph contains two P labels, split or remove one idea. If it has a Point and Example but no Why, add the missing explanation. If every sentence begins with a memorised linker, delete half and see whether sentence order can carry the meaning.</p>

