  <h2>The record–tag–repair–repeat method</h2>
  <ol>
    <li><strong>Record:</strong> answer three questions without restarting or reading a script.</li>
    <li><strong>Tag:</strong> transcribe one answer exactly and mark repeated grammar errors or vague vocabulary.</li>
    <li><strong>Repair:</strong> rewrite only two sentences, preserving your original idea and speaking style.</li>
    <li><strong>Repeat:</strong> answer the question again from one-line notes, not from the corrected transcript.</li>
  </ol>
  <p>The final step matters. Reading a perfect sentence proves reading control. Producing the pattern again while thinking proves that it is becoming available in speech.</p>

