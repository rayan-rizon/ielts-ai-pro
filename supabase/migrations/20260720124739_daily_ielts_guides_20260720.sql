  <h2>Use the Point–Why–Result–Proof chain</h2>
  <p>Before writing a body paragraph, make four short notes. They are not a rigid template; they are a logic check.</p>
  <ol>
    <li><strong>Point:</strong> What is the one claim this paragraph will make?</li>
    <li><strong>Why:</strong> What mechanism or reason makes the claim true?</li>
    <li><strong>Result:</strong> What consequence follows from that reason?</li>
    <li><strong>Proof:</strong> What realistic example or situation makes the chain concrete?</li>
  </ol>
  <p>Suppose the question asks whether cities should charge drivers to enter crowded centres. Your notes might be: <em>charge discourages optional trips → fewer cars at peak time → buses move faster → commuters choose public transport when journey times become reliable</em>.</p>
  <p>Now the paragraph has movement. You can decide whether a connector is needed after you know the relationship.</p>

