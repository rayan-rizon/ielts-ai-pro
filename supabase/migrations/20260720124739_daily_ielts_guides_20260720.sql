  <blockquote><p>Coherence is the route your argument follows. Cohesion is the language that helps the reader stay on that route.</p></blockquote>

  <h2>What changes from Band 6 to Band 7?</h2>
  <p>IELTS assesses Writing through four criteria, and coherence and cohesion is one of them. Official preparation guidance distinguishes clear overall progression at Band 6 from logical organisation and clear progression throughout the response at Band 7. That difference is easy to miss: an essay may have an introduction, body paragraphs, and a conclusion, but still lose its thread inside a paragraph.</p>
