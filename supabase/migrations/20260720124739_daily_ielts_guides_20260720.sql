      <tr><td>Progression</td><td>The essay moves forward overall, with a few abrupt or unclear steps.</td><td>Each sentence has a clear job in developing the point.</td></tr>
      <tr><td>Cohesive devices</td><td>Linking can sound mechanical or repetitive.</td><td>Connectors, reference words, and sentence structure are used flexibly and appropriately.</td></tr>
      <tr><td>Referencing</td><td>Words such as <em>this</em> or <em>they</em> sometimes have an unclear target.</td><td>The reader can identify exactly what each reference points to.</td></tr>
