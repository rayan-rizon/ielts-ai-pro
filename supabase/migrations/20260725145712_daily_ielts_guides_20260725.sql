  <h2>Know the official sentence-completion rules</h2>
  <p>In this question type, you complete each sentence using words from the passage. The instruction gives a word and number limit, which can change between tasks. Writing more than that limit loses the mark. The completed sentences follow the same order as the information in the text.</p>
