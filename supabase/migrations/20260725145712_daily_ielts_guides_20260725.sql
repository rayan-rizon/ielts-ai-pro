      <tr><td>Copying a British or American accent quickly</td><td>Attention shifts away from ideas and natural fluency</td><td>Keep your voice and target specific clarity problems</td></tr>
      <tr><td>Speaking unusually slowly</td><td>Words may be clearer but the answer becomes fragmented</td><td>Use thought groups and a comfortable pace</td></tr>
