  <h2>What an IELTS process diagram asks you to do</h2>
  <p>In Academic Writing Task 1, a diagram may show the stages of a process, how something works, or how an object or event develops. You need to describe, summarise, or explain the visual in your own words and write at least 150 words. A practical target is about 20 minutes so Task 2 still receives the larger share of your Writing time.</p>
