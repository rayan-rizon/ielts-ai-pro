  <h2>What IELTS Speaking assesses</h2>
  <p>The four Speaking criteria are fluency and coherence, lexical resource, grammatical range and accuracy, and pronunciation. They carry equal weight. Pronunciation is therefore important, but it is one quarter of a larger performance—not a separate accent imitation test.</p>
  <p>Official IDP guidance published in 2026 says accents do not affect the score when the examiner can understand the speaker clearly. It highlights clear pronunciation, natural intonation, and correct word stress rather than a preferred national accent.</p>

