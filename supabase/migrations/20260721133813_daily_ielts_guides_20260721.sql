  <p>This four-box note is your prompt lock. If an idea does not connect to the focus, instruction, and position, it does not enter the essay—even when the idea sounds impressive.</p>

  <h2>Use the because–therefore relevance test</h2>
  <p>Test each body-paragraph idea with one sentence:</p>
  <p><strong>I believe [position] because [paragraph reason]; therefore [direct effect on the exact question].</strong></p>
  <p>For the example above: “I believe governments should increase vocational funding because some industries face practical skill shortages; therefore targeted courses can connect public spending more directly to unfilled jobs.”</p>
  <p>If the <em>therefore</em> clause returns to the wording of the task, the idea is probably relevant. If it returns only to the broad topic—“therefore education is important”—the paragraph is still too general.</p>

  <h2>A worked drift-and-repair example</h2>
  <p><strong>Drifting version:</strong> “Universities have existed for centuries and teach many interesting subjects. Students also meet people from different backgrounds, which is good for society. Education helps countries develop.”</p>
  <p>Nothing here is automatically false, but the paragraph avoids the funding comparison. It could be pasted into dozens of education essays.</p>
  <p><strong>Prompt-locked version:</strong> “Removing university funding entirely would be short-sighted because economies also need doctors, engineers, and researchers whose training depends on degree-level study. Governments can expand vocational places for immediate shortages without treating every university course as a lower public priority.”</p>
  <p>The repaired version makes a claim about the exact decision, explains why, and keeps the position balanced.</p>

  <aside><p><strong>One-sentence warning:</strong> if a paragraph could answer a different question with only one noun changed, it is probably too generic.</p></aside>

  <h2>Stop overwriting with a paragraph budget</h2>
  <p>More words do not create a higher band by themselves. Use a job-based budget instead of chasing a perfect total:</p>
  <ol>
    <li><strong>Topic sentence:</strong> one clear paragraph claim.</li>
    <li><strong>Explanation:</strong> two or three sentences showing the mechanism or reason.</li>
    <li><strong>Example:</strong> one realistic illustration only when it strengthens the explanation.</li>
    <li><strong>Link back:</strong> a short consequence that reconnects to the task.</li>
  </ol>
  <p>When those four jobs are complete, stop. A second example often repeats the first or opens a new idea that you do not have time to develop.</p>

  <h2>Run the margin test while you practise</h2>
  <p>After writing each paragraph, place a short note in the margin: <em>What does this prove about the question?</em> Answer in eight words or fewer. If you cannot, underline the sentence where the paragraph drifted. Remove or rewrite from that point instead of polishing the vocabulary.</p>
  <p>Then review the full essay with three checks:</p>
  <ul>
    <li>Does the introduction answer every instruction word?</li>
    <li>Does each body paragraph support the same position?</li>
    <li>Does the conclusion repeat the answer rather than introduce a rescue idea?</li>
  </ul>

