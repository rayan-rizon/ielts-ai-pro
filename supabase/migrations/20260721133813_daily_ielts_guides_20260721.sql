    <tbody>
      <tr><td>Topic</td><td>What broad subject is being discussed?</td><td>Public funding for education</td></tr>
      <tr><td>Focus</td><td>Which narrow comparison, cause, or problem matters?</td><td>Vocational training versus university</td></tr>
      <tr><td>Instruction</td><td>What must I do: agree, discuss, explain causes, or propose solutions?</td><td>Give the extent of my agreement</td></tr>
