      <tr><td>L — Locate</td><td>Look at the next unanswered question, not the missed one.</td><td>Gives your attention a new target.</td></tr>
      <tr><td>E — Expect</td><td>Identify one anchor: a name, topic change, option difference, or required word type.</td><td>Creates a signal you can listen for.</td></tr>
      <tr><td>A — Attend</td><td>Listen for meaning around the anchor.</td><td>Rejoins the conversation or monologue.</td></tr>
      <tr><td>S/E — Stay / Evaluate later</td><td>Keep moving; revisit only when the recording or section permits.</td><td>Protects the remaining marks.</td></tr>
    </tbody>
