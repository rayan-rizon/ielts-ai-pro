  <h2>Know the difference between a blank and being lost</h2>
  <p>A <strong>blank</strong> means you know where the audio is, but you did not catch one answer. Being <strong>lost</strong> means you no longer know which question the speakers are discussing. Use different responses:</p>
  <ul>
    <li>For one blank, move directly to the next question and listen for its anchor.</li>
    <li>When lost, scan two or three upcoming questions for a clear shift—a new speaker, place, stage, reason, or opinion—and rejoin there.</li>
    <li>Do not scan the entire page. Too much visual searching competes with listening.</li>
  </ul>

