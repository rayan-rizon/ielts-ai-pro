  <p>For each wrong answer, spend no more than 90 focused seconds on four steps:</p>
  <ol>
    <li>Find the exact evidence or confirm that the information is absent.</li>
    <li>Underline the question phrase and the passage phrase that express the same or opposing meaning.</li>
