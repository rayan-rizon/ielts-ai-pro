  <p>You are halfway through the second body paragraph when a worrying thought appears: <em>This sounds intelligent, but is it answering the question?</em> You add another example to make the essay feel safer. Five minutes later, the response is longer, the ending is rushed, and the new material has moved even further from the task.</p>
  <p>This is not mainly a vocabulary problem. It is a control problem. Recent learners have described writing too much, losing the neat shape of the essay, and gradually straying from the topic. The fix is to lock every paragraph to the exact task before you start expanding it.</p>

  <blockquote><p>Your essay is not about everything you know on the subject. It is a direct answer to one specific instruction.</p></blockquote>

  <h2>Why “related” is not the same as “relevant”</h2>
  <p>Official IELTS guidance says Task 2 should address the most relevant issues and answer the task fully. Task response assesses how accurately, appropriately, and relevantly you cover the requirements. IELTS also warns that very long answers can leave less time for checking and may contain ideas that are not directly relevant.</p>
  <p>Imagine the question asks whether governments should fund vocational training <em>instead of</em> university education. A paragraph about the general importance of education is related to the topic. It is not yet relevant to the choice in the question. Relevance appears when the paragraph explains how funding one route rather than the other affects people, employers, or public resources.</p>

  <h2>Build a prompt lock in four boxes</h2>
  <p>Before brainstorming examples, divide the question into four parts. Write only a few words in each box.</p>
  <table>
