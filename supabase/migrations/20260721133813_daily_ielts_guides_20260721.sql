  <h2>Use the 10-second RELEASE reset</h2>
  <p>The name is longer than the action. Train the sequence until it feels automatic:</p>
  <table>
    <thead><tr><th scope="col">Step</th><th scope="col">Action</th><th scope="col">Reason</th></tr></thead>
