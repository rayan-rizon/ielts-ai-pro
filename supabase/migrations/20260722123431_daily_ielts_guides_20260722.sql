  <h2>What to do when no idea arrives</h2>
  <p>A short thinking pause is different from giving up. Use the question itself to create a decision:</p>
  <ol>
    <li>Choose a group: individuals, families, schools, employers, or governments.</li>
    <li>Choose an effect: time, cost, access, behaviour, health, or fairness.</li>
    <li>Connect them in one cautious claim.</li>
  </ol>
