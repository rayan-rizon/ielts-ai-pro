  <p>The examiner asks whether cities should limit private cars. You understand every word, but your first reason opens three more ideas. A few sentences later, you are discussing public health, remote work, fuel prices, and a holiday you took last year. You are still speaking, yet the answer no longer has a centre.</p>
  <p>Recent IELTS learners have described this exact pressure: ideas are available, but fluency drops or the response becomes less coherent and relevant when Part 3 turns abstract. The solution is not to memorise impressive opinions. It is to give each answer one controllable shape.</p>

  <blockquote><p>A strong Part 3 answer does not need every possible idea. It needs one position that the listener can follow.</p></blockquote>

  <h2>Know the job of Part 3</h2>
  <p>IELTS describes Part 3 as a four-to-five-minute discussion of issues connected to Part 2 in a more general and abstract way. It tests your ability to explain opinions and to analyse, discuss, and speculate. Your performance is assessed across fluency and coherence, lexical resource, grammatical range and accuracy, and pronunciation.</p>
  <p>That means your job is not to discover the perfect social policy in real time. Your job is to make a reasonable idea understandable, develop it, and respond naturally if the examiner asks you to go deeper.</p>

  <h2>Use the five-step POINT framework</h2>
  <p>POINT gives you a route through an unfamiliar question without turning the answer into a script.</p>
  <table>
    <thead><tr><th scope="col">Step</th><th scope="col">What to do</th><th scope="col">Useful self-question</th></tr></thead>
    <tbody>
      <tr><td>P — Pause</td><td>Take one natural beat and choose a direction.</td><td>What is my simplest honest position?</td></tr>
      <tr><td>O — Opinion</td><td>State one answer, even if it needs qualification later.</td><td>Mostly yes, mostly no, or it depends on what?</td></tr>
      <tr><td>I — Insight</td><td>Explain the main reason or mechanism.</td><td>Why would this happen?</td></tr>
      <tr><td>N — Narrow example</td><td>Give one short example, comparison, or consequence.</td><td>What makes the reason concrete?</td></tr>
      <tr><td>T — Tie back</td><td>Return to the question or add one careful limit.</td><td>So what is my final answer?</td></tr>
    </tbody>
  </table>
  <p>The framework is a sequence of thinking jobs, not five sentences you must announce. In a short answer, the opinion and insight may be enough. In a deeper answer, the example and tie-back stop the idea from drifting.</p>

  <h2>A worked Part 3 answer</h2>
  <p><strong>Question:</strong> Should cities discourage people from using private cars?</p>
  <p><strong>Rambling version:</strong> “Yes, because traffic is bad, and there are many people now, and public transport is also important. In my city buses are crowded, although some people work online, and petrol is expensive, so there are many different issues.”</p>
  <p><strong>POINT version:</strong> “Cities should probably discourage car use in the busiest areas because road space is limited. For example, a reliable park-and-ride service can reduce the number of vehicles entering the centre without removing people’s ability to travel. However, restrictions only make sense when commuters have a practical alternative.”</p>
  <p>The second answer is not longer or more academic. It is easier to follow because each sentence supports the same position.</p>

